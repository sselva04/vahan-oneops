-- Raw material of a part. Sizes are in mm; what dim_a/b/c mean depends on the shape:
--   BLOCK  length, width, thickness      ROUND  diameter, length      TUBE  outer diameter, inner diameter, length
--   MANUAL weight per piece typed in (manual_weight_kg), no size
ALTER TABLE child_part ADD COLUMN material_id      BIGINT;
ALTER TABLE child_part ADD COLUMN rm_shape         VARCHAR(10);
ALTER TABLE child_part ADD COLUMN rm_dim_a         NUMERIC(10, 2);
ALTER TABLE child_part ADD COLUMN rm_dim_b         NUMERIC(10, 2);
ALTER TABLE child_part ADD COLUMN rm_dim_c         NUMERIC(10, 2);
ALTER TABLE child_part ADD COLUMN manual_weight_kg NUMERIC(10, 3);
-- Weighed weight of the stock for the whole part quantity (like the RM tracker sheet).
ALTER TABLE child_part ADD COLUMN actual_weight_kg NUMERIC(10, 3);
-- Price per kg at the time the raw material was saved, so a later price change does not rewrite old costs.
ALTER TABLE child_part ADD COLUMN rm_rate_per_kg   NUMERIC(10, 2);
ALTER TABLE child_part ADD CONSTRAINT fk_child_part_material FOREIGN KEY (material_id) REFERENCES material (id);
ALTER TABLE child_part ADD CONSTRAINT ck_child_part_actual CHECK (actual_weight_kg IS NULL OR actual_weight_kg > 0);
CREATE INDEX ix_child_part_material ON child_part (material_id);
