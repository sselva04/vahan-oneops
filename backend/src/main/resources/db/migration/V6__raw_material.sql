-- Central list of raw materials (density for the weight calculation, price per kg), and the raw material
-- of each part. Only ADDS a table and columns: existing parts simply have no raw material yet.

CREATE TABLE material (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(80)    NOT NULL,
    density        NUMERIC(6, 3)  NOT NULL,   -- g/cm3
    price_per_kg   NUMERIC(10, 2),            -- empty until the admin enters it
    active         BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_material_name UNIQUE (name),
    CONSTRAINT ck_material_density CHECK (density > 0),
    CONSTRAINT ck_material_price CHECK (price_per_kg IS NULL OR price_per_kg >= 0)
);

