-- Release B: in-house VMC machine-hour log and the tool register.
-- Everything here only ADDS tables, so the previous version of the app keeps working on this schema
-- and can be rolled back to at any time.

-- Small key/value settings (machine hourly rate and tax rate).
CREATE TABLE app_setting (
    setting_key   VARCHAR(60)  PRIMARY KEY,
    setting_value VARCHAR(200) NOT NULL
);
INSERT INTO app_setting (setting_key, setting_value) VALUES ('machine_hour_rate', '450');
INSERT INTO app_setting (setting_key, setting_value) VALUES ('machine_hour_tax_percent', '18');

-- One row per VMC job, like a row of the "VMC Hr Monitering" sheet.
-- The rate and tax rate are copied onto the row, so changing the defaults later never changes old entries.
CREATE TABLE machine_hour_entry (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_date         DATE           NOT NULL,
    project_id         BIGINT         NOT NULL,
    child_part_id      BIGINT,
    quantity           INTEGER        NOT NULL,
    hardened           BOOLEAN        NOT NULL DEFAULT FALSE,
    design_minutes     INTEGER        NOT NULL DEFAULT 0,
    setting_minutes    INTEGER        NOT NULL DEFAULT 0,
    run_minutes        INTEGER        NOT NULL DEFAULT 0,
    idle_minutes       INTEGER        NOT NULL DEFAULT 0,
    power_cut_minutes  INTEGER        NOT NULL DEFAULT 0,
    rate_per_hour      NUMERIC(10, 2) NOT NULL,
    tax_percent        NUMERIC(5, 2)  NOT NULL,
    billable_hours     NUMERIC(10, 2) NOT NULL,
    amount             NUMERIC(12, 2) NOT NULL,
    tax_amount         NUMERIC(12, 2) NOT NULL,
    remarks            VARCHAR(500),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_mhe_project FOREIGN KEY (project_id) REFERENCES project (id),
    CONSTRAINT fk_mhe_part FOREIGN KEY (child_part_id) REFERENCES child_part (id),
    CONSTRAINT ck_mhe_quantity CHECK (quantity > 0),
    CONSTRAINT ck_mhe_minutes CHECK (design_minutes >= 0 AND setting_minutes >= 0 AND run_minutes >= 0
                                     AND idle_minutes >= 0 AND power_cut_minutes >= 0),
    CONSTRAINT ck_mhe_money CHECK (rate_per_hour >= 0 AND tax_percent >= 0 AND amount >= 0 AND tax_amount >= 0)
);
CREATE INDEX ix_mhe_date ON machine_hour_entry (entry_date);
CREATE INDEX ix_mhe_project ON machine_hour_entry (project_id);

-- One row per physical tool, like the "Tool Stock Details" sheet.
CREATE TABLE tool_item (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_type          VARCHAR(60)    NOT NULL,
    description        VARCHAR(200)   NOT NULL,
    item_code          VARCHAR(60),
    tool_size          VARCHAR(60),
    cost               NUMERIC(12, 2) NOT NULL DEFAULT 0,
    purchased_on       DATE,
    issued_on          DATE,
    broken_on          DATE,
    scrapped_on        DATE,
    broken_reason      VARCHAR(300),
    broken_project_id  BIGINT,
    broken_part_id     BIGINT,
    remarks            VARCHAR(500),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_tool_broken_project FOREIGN KEY (broken_project_id) REFERENCES project (id),
    CONSTRAINT fk_tool_broken_part FOREIGN KEY (broken_part_id) REFERENCES child_part (id),
    CONSTRAINT ck_tool_cost CHECK (cost >= 0)
);

CREATE TABLE tool_resharpen (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_item_id   BIGINT         NOT NULL,
    resharpened_on DATE,
    cost           NUMERIC(12, 2) NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_resharpen_tool FOREIGN KEY (tool_item_id) REFERENCES tool_item (id),
    CONSTRAINT ck_resharpen_cost CHECK (cost >= 0)
);
CREATE INDEX ix_resharpen_tool ON tool_resharpen (tool_item_id);
