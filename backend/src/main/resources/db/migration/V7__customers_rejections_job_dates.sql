-- One fixed customer per project. Empty for projects created before this release.
ALTER TABLE project ADD COLUMN customer_id BIGINT;
ALTER TABLE project ADD CONSTRAINT fk_project_customer FOREIGN KEY (customer_id) REFERENCES customer (id);
CREATE INDEX ix_project_customer ON project (customer_id);

-- When a job was sent to the supplier and when it came back.
ALTER TABLE part_stage ADD COLUMN sent_on     DATE;
ALTER TABLE part_stage ADD COLUMN received_on DATE;

-- A part spoiled at a supplier. Debit = rejected qty x part cost - machining cost, unless the admin typed an amount.
-- supplier_id is copied from the stage at that moment, so later changes to the stage do not move old debits.
CREATE TABLE rejection (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_stage_id   BIGINT         NOT NULL,
    supplier_id     BIGINT         NOT NULL,
    rejected_qty    INTEGER        NOT NULL,
    part_cost       NUMERIC(12, 2) NOT NULL,
    machining_cost  NUMERIC(12, 2) NOT NULL,
    debit_amount    NUMERIC(12, 2) NOT NULL,
    debit_manual    BOOLEAN        NOT NULL DEFAULT FALSE,
    bill_no         VARCHAR(40),
    rejected_on     DATE,
    remarks         VARCHAR(500),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_rejection_stage    FOREIGN KEY (part_stage_id) REFERENCES part_stage (id),
    CONSTRAINT fk_rejection_supplier FOREIGN KEY (supplier_id)   REFERENCES supplier (id),
    CONSTRAINT ck_rejection_qty      CHECK (rejected_qty > 0),
    CONSTRAINT ck_rejection_costs    CHECK (part_cost >= 0 AND machining_cost >= 0 AND debit_amount >= 0)
);
CREATE INDEX ix_rejection_stage    ON rejection (part_stage_id);
CREATE INDEX ix_rejection_supplier ON rejection (supplier_id);
