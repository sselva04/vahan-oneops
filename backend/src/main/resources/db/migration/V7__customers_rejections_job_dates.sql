-- Release A: customers, supplier rejections with debit, and sent/received dates on outsourced jobs.
-- Everything here only ADDS tables and nullable columns, so the previous version of the app keeps working
-- on this schema and can be rolled back to at any time.

CREATE TABLE customer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_customer_name UNIQUE (name)
);

