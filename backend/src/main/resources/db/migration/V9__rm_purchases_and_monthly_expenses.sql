-- Release C: raw material purchase log and monthly expenses for the turnover/profit report.
-- Everything here only ADDS tables, so the previous version of the app keeps working on this schema
-- and can be rolled back to at any time.

-- One row per raw material purchase, like a row of the "RM TRACKERS" sheet.
CREATE TABLE rm_purchase (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_part_id BIGINT         NOT NULL,
    supplier_id   BIGINT         NOT NULL,
    weight_kg     NUMERIC(12, 3) NOT NULL,
    rate_per_kg   NUMERIC(10, 2) NOT NULL,
    total_cost    NUMERIC(12, 2) NOT NULL,
    in_date       DATE           NOT NULL,
    out_date      DATE,
    remarks       VARCHAR(500),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_rm_purchase_part FOREIGN KEY (child_part_id) REFERENCES child_part (id),
    CONSTRAINT fk_rm_purchase_supplier FOREIGN KEY (supplier_id) REFERENCES supplier (id),
    CONSTRAINT ck_rm_purchase_weight CHECK (weight_kg > 0),
    CONSTRAINT ck_rm_purchase_money CHECK (rate_per_kg >= 0 AND total_cost >= 0)
);
CREATE INDEX ix_rm_purchase_in_date ON rm_purchase (in_date);
CREATE INDEX ix_rm_purchase_part ON rm_purchase (child_part_id);

-- The two expenses typed in each month in the "VMC Turnover" sheet. month_key looks like 2026-11.
CREATE TABLE monthly_expense (
    month_key   VARCHAR(7)     PRIMARY KEY,
    consumables NUMERIC(12, 2) NOT NULL DEFAULT 0,
    salary      NUMERIC(12, 2) NOT NULL DEFAULT 0,
    notes       VARCHAR(500),
    CONSTRAINT ck_monthly_expense CHECK (consumables >= 0 AND salary >= 0)
);
