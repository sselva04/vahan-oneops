-- Outside workshops (suppliers) and the processes each one does, plus the details of a stage
-- that is given to a supplier. Everything here only ADDS tables and columns: existing projects,
-- parts and stages are untouched, and the previous version of the app keeps working on this schema.

CREATE TABLE supplier (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(200) NOT NULL,
    address    VARCHAR(300),
    map_url    VARCHAR(500),
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_supplier_name UNIQUE (name)
);

-- One row per process a supplier does, each with its own contact (as in Vahan's supplier sheet).
CREATE TABLE supplier_process (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id     BIGINT       NOT NULL,
    stage_master_id BIGINT       NOT NULL,
    contact_person  VARCHAR(120),
    contact_phone   VARCHAR(80),
    CONSTRAINT uq_supplier_process UNIQUE (supplier_id, stage_master_id),
    CONSTRAINT fk_supplier_process_supplier FOREIGN KEY (supplier_id)     REFERENCES supplier (id),
    CONSTRAINT fk_supplier_process_stage    FOREIGN KEY (stage_master_id) REFERENCES stage_master (id)
);
CREATE INDEX ix_supplier_process_stage ON supplier_process (stage_master_id);

-- A stage is either done in-house (supplier_id is empty) or given to a supplier.
ALTER TABLE part_stage ADD COLUMN supplier_id            BIGINT;
ALTER TABLE part_stage ADD COLUMN job_qty                INTEGER;
ALTER TABLE part_stage ADD COLUMN rate_per_unit          NUMERIC(12, 2);
ALTER TABLE part_stage ADD COLUMN pre_inspection_done    BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE part_stage ADD COLUMN final_inspection_done  BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE part_stage ADD COLUMN remarks                VARCHAR(500);
ALTER TABLE part_stage ADD CONSTRAINT fk_part_stage_supplier FOREIGN KEY (supplier_id) REFERENCES supplier (id);
ALTER TABLE part_stage ADD CONSTRAINT ck_part_stage_job_qty  CHECK (job_qty IS NULL OR job_qty > 0);
ALTER TABLE part_stage ADD CONSTRAINT ck_part_stage_rate     CHECK (rate_per_unit IS NULL OR rate_per_unit >= 0);
CREATE INDEX ix_part_stage_supplier ON part_stage (supplier_id);
