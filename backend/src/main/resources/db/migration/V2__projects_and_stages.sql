-- A project is identified by its drawing number. Each project has child parts,
-- and each child part has its own ordered list of stages, each with one owner.

CREATE TABLE stage_master (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(80) NOT NULL,
    active BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_stage_master_name UNIQUE (name)
);

CREATE TABLE project (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drawing_no VARCHAR(60)  NOT NULL,
    name       VARCHAR(200) NOT NULL,
    created_by BIGINT       NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_project_drawing_no UNIQUE (drawing_no),
    CONSTRAINT fk_project_created_by FOREIGN KEY (created_by) REFERENCES app_user (id)
);

CREATE TABLE child_part (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT       NOT NULL,
    drawing_no VARCHAR(60)  NOT NULL,
    name       VARCHAR(200) NOT NULL,
    quantity   INTEGER      NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_child_part_drawing_no UNIQUE (drawing_no),
    CONSTRAINT fk_child_part_project FOREIGN KEY (project_id) REFERENCES project (id),
    CONSTRAINT ck_child_part_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_child_part_project ON child_part (project_id);

CREATE TABLE part_stage (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_part_id   BIGINT      NOT NULL,
    stage_master_id BIGINT      NOT NULL,
    sequence_no     INTEGER     NOT NULL,
    assignee_id     BIGINT,
    status          VARCHAR(20) NOT NULL,
    due_date        DATE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_part_stage_sequence UNIQUE (child_part_id, sequence_no),
    CONSTRAINT fk_part_stage_part     FOREIGN KEY (child_part_id)   REFERENCES child_part (id),
    CONSTRAINT fk_part_stage_master   FOREIGN KEY (stage_master_id) REFERENCES stage_master (id),
    CONSTRAINT fk_part_stage_assignee FOREIGN KEY (assignee_id)     REFERENCES app_user (id)
);
CREATE INDEX ix_part_stage_assignee ON part_stage (assignee_id);

